test_that("write, commit, reopen", {
  r <- new_repo()
  repo <- ic_repo_open(r$dir)
  expect_equal(ic_lookup(repo), r$id)
  a <- ic_ancestry(repo)
  expect_equal(a$message[1], "init")
  expect_equal(jsonlite::fromJSON(a$metadata[1])$author, "test")
  s <- ic_session_readonly(repo)
  expect_error(ic_list(s, "x/c"), "group or array")
  expect_setequal(grep("/c/", ic_list(s, "x"), value = TRUE), c("x/c/0/0", "x/c/0/1", "x/c/1/0", "x/c/1/1"))
  expect_identical(ic_get(s, "x/c/1/0"), i32(rep(2, 4)))
  expect_equal(ic_nodes(s)$path, c("/", "/x"))
  expect_error(ic_set(s, "x/c/0/0", i32(1:4)), class = "icechunk_error")
})

test_that("status, discard, amend, flush, delete", {
  r <- new_repo()
  s <- ic_session_writable(r$repo)
  ic_set(s, "x/c/0/0", i32(9:12))
  st <- ic_status(s)
  expect_equal(st$updated_chunks$coord, "0,0")
  ic_discard(s)
  expect_false(ic_session_info(s)$has_uncommitted_changes)
  ic_delete(s, "x/c/1/1")
  id2 <- ic_commit(s, "drop a chunk")
  s <- ic_session_writable(r$repo)
  ic_set(s, "x/c/0/0", i32(9:12))
  id3 <- ic_amend(s, "drop a chunk, rewrite another")
  a <- ic_ancestry(r$repo)
  expect_false(id2 %in% a$snapshot_id)
  expect_equal(a$snapshot_id[1], id3)
  expect_null(ic_get(ic_session_readonly(r$repo), "x/c/1/1"))
  s <- ic_session_writable(r$repo)
  ic_set(s, "x/c/0/1", i32(0:3))
  anon <- ic_flush(s, "anonymous")
  expect_equal(ic_lookup(r$repo), id3)  # branch did not move
  expect_identical(ic_get(ic_session_readonly(r$repo, snapshot = anon), "x/c/0/1"), i32(0:3))
})

test_that("branches and tags", {
  r <- new_repo()
  ic_branch_create(r$repo, "dev", r$id)
  ic_tag_create(r$repo, "v0", r$id)
  s <- ic_session_writable(r$repo, "dev")
  ic_set(s, "x/c/0/0", i32(c(7, 7, 7, 7)))
  dev <- ic_commit(s, "dev change")
  expect_setequal(ic_branches(r$repo)$name, c("main", "dev"))
  expect_equal(ic_tags(r$repo)$snapshot_id, r$id)
  d <- ic_diff(r$repo, list(branch = "main"), list(branch = "dev"))
  expect_equal(d$updated_chunks$coord, "0,0")
  ic_branch_reset(r$repo, "main", dev, from = r$id)
  expect_equal(ic_lookup(r$repo, "main"), dev)
  expect_error(ic_branch_reset(r$repo, "main", r$id, from = r$id), class = "icechunk_error")
  ic_branch_delete(r$repo, "dev")
  ic_tag_delete(r$repo, "v0")
  expect_equal(ic_branches(r$repo)$name, "main")
  expect_equal(nrow(ic_tags(r$repo)), 0L)
})

test_that("concurrent sessions conflict; rebase resolves non-overlapping", {
  r <- new_repo()
  a <- ic_session_writable(r$repo)
  b <- ic_session_writable(r$repo)
  ic_set(a, "x/c/0/0", i32(rep(10, 4)))
  ic_set(b, "x/c/1/1", i32(rep(11, 4)))
  ic_commit(a, "a")
  expect_error(ic_commit(b, "b"), class = "icechunk_conflict")
  ic_rebase(b)
  ic_commit(b, "b after rebase")
  s <- ic_session_readonly(r$repo)
  expect_identical(ic_get(s, "x/c/0/0"), i32(rep(10, 4)))
  expect_identical(ic_get(s, "x/c/1/1"), i32(rep(11, 4)))

  # overlapping: detect fails, basic(ours) wins
  a <- ic_session_writable(r$repo)
  b <- ic_session_writable(r$repo)
  ic_set(a, "x/c/0/1", i32(rep(20, 4)))
  ic_set(b, "x/c/0/1", i32(rep(21, 4)))
  ic_commit(a, "a2")
  expect_error(ic_commit(b, "b2"), class = "icechunk_conflict")
  expect_error(ic_rebase(b), class = "icechunk_conflict")
  ic_rebase(b, "basic", on_chunk = "ours")
  ic_commit(b, "b2 ours")
  expect_identical(ic_get(ic_session_readonly(r$repo), "x/c/0/1"), i32(rep(21, 4)))
})

test_that("session bytes roundtrip, fork, merge", {
  r <- new_repo()
  ro <- ic_session_readonly(r$repo)
  b <- ic_session_bytes(ro)
  expect_s3_class(b, "icechunk_session_bytes")
  expect_identical(rawToChar(b[1:4]), "ICR1")
  ro2 <- ic_session_from_bytes(b)
  expect_identical(ic_get(ro2, "x/c/0/1"), ic_get(ro, "x/c/0/1"))

  base <- ic_session_writable(r$repo)
  f1 <- ic_session_fork(base)
  f2 <- ic_session_fork(base)
  expect_true(ic_session_info(f1)$is_fork)
  # pretend these are remote workers: only bytes cross
  w1 <- ic_session_from_bytes(ic_session_bytes(f1))
  w2 <- ic_session_from_bytes(ic_session_bytes(f2))
  ic_set(w1, "x/c/0/0", i32(rep(100, 4)))
  ic_set(w2, "x/c/1/0", i32(rep(200, 4)))
  ic_session_merge(base, ic_session_bytes(w1))
  ic_session_merge(base, ic_session_bytes(w2))
  ic_commit(base, "merged workers")
  s <- ic_session_readonly(r$repo)
  expect_identical(ic_get(s, "x/c/0/0"), i32(rep(100, 4)))
  expect_identical(ic_get(s, "x/c/1/0"), i32(rep(200, 4)))
})

test_that("handoff header rejects foreign versions", {
  r <- new_repo()
  b <- unclass(ic_session_bytes(ic_session_readonly(r$repo)))
  n <- readBin(b[5:6], "integer", size = 2, signed = FALSE, endian = "little")
  bad <- c(b[1:4], writeBin(5L, raw(), size = 2, endian = "little"), charToRaw("0.0.0"), b[-(1:(6 + n))])
  expect_error(ic_session_from_bytes(bad), class = "icechunk_version")
  expect_error(ic_session_from_bytes(bad), "0.0.0")
  expect_error(ic_session_from_bytes(charToRaw("nope")), class = "icechunk_version")
})

test_that("virtual refs: write, authorise, read, chunk table", {
  d <- tempfile("vsrc"); dir.create(d)
  src <- file.path(d, "data.bin")
  writeBin(i32(0:15), src)
  prefix <- paste0("file://", normalizePath(d), "/")
  repo <- ic_repo_create(ic_storage_local(tempfile("icv")),
                         containers = ic_container(prefix, "local", path = normalizePath(d)),
                         authorize = prefix)
  ic_repo_save_config(repo)
  s <- ic_session_writable(repo)
  ic_set(s, "zarr.json", grp_meta())
  ic_set(s, "v/zarr.json", arr_meta(16, 4))
  ic_set_virtual_ref(s, "v/c/0", paste0(prefix, "data.bin"), 0, 16)
  refs <- data.frame(coord = c("1", "2", "3"), location = paste0(prefix, "data.bin"),
                     offset = c(16, 32, 48), length = 16)
  expect_equal(ic_set_virtual_refs(s, "/v", refs), 0L)
  ic_commit(s, "virtual")
  r <- ic_chunk_refs(ic_session_readonly(repo), "/v")
  expect_equal(r$offset, c(0, 16, 32, 48))
  expect_equal(unique(r$kind), "virtual")
  # a fresh open must authorise again
  st <- repo$storage
  expect_error(ic_get(ic_session_readonly(ic_repo_open(st)), "v/c/2"), class = "icechunk_error")
  s2 <- ic_session_readonly(ic_repo_open(st, authorize = prefix))
  expect_identical(ic_get(s2, "v/c/2"), i32(8:11))
  expect_error(ic_set_virtual_ref(ic_session_writable(repo), "v/c/0", "s3://elsewhere/x", 0, 4),
               class = "icechunk_error")
})

test_that("static virtual-chunk keys are inside session bytes (documented)", {
  secret <- "SECRETzzzz1234567890"
  repo <- ic_repo_create(ic_storage_local(tempfile()),
    containers = ic_container("s3://some-bucket/", "s3", region = "us-east-1"),
    authorize = list("s3://some-bucket/" = ic_cred_s3("static", "AKIDzzzz", secret)))
  b <- unclass(ic_session_bytes(ic_session_readonly(repo)))
  expect_true(length(grepRaw(secret, b, fixed = TRUE)) > 0)
  repo2 <- ic_repo_create(ic_storage_local(tempfile()),
    containers = ic_container("s3://some-bucket/", "s3", region = "us-east-1"),
    authorize = list("s3://some-bucket/" = ic_cred_s3("from_env")))
  b2 <- unclass(ic_session_bytes(ic_session_readonly(repo2)))
  expect_length(grepRaw(secret, b2, fixed = TRUE), 0)
})
